/**
 * CSV 单元格转义。
 *
 * 除了常规的引号加倍，还要处理公式注入：Excel/WPS 打开 CSV 时，凡是以 = + - @ 开头的
 * 单元格都会被当成公式执行。补贴数据里的姓名、备注、失败原因都是人手录进去的，
 * 一条 `=cmd|'/c calc'!A1` 就能在打开报表的人机器上跑命令。
 * 前面补一个单引号让 Excel 按纯文本处理；显示时不会带出这个引号。
 *
 * 制表符/回车开头也一并挡掉——部分版本会把它们当成前缀空白继续解析后面的公式。
 */
export function csvCell(v) {
  let s = v == null ? '' : String(v)
  if (/^[=+\-@\t\r]/.test(s)) s = "'" + s
  return `"${s.replace(/"/g, '""')}"`
}
